/** Emit Harness's lazy client-factory ABI using only Node's standard library. */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const sources = ['client/controller.mjs', 'client/view.mjs', 'client/index.mjs'];
const sections = [];
for (const source of sources) {
  const code = await readFile(new URL(source, root), 'utf8');
  // This explicit source list has only named, package-local imports and declaration exports.
  // Refuse unsupported syntax so a future edit cannot silently ship an incomplete bundle.
  const body = code.replace(/^import \{[^\n]+\} from '\.\/(?:controller|view)\.mjs';\r?\n/gm, '')
    .replace(/^export (?=(?:const|function|async function) )/gm, '');
  if (/^\s*(?:import|export)\b/m.test(body)) throw new Error(`Unsupported module syntax in ${source}`);
  sections.push(`// ${source}\n${body.trimEnd()}`);
}
const bundle = `// Generated by node scripts/build-ui.mjs. Edit client/*.mjs instead.\nwindow.__ModuleLoader__.load({ id: 'dsh-strong-skills', factory: (require) => {\n'use strict';\n${sections.join('\n\n')}\n\nreturn createClientPlugin(require('react'));\n} });\n`;
const target = new URL('client/client.js', root);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== bundle) throw new Error('Client bundle is stale; run node scripts/build-ui.mjs');
} else {
  await writeFile(target, bundle, 'utf8');
  process.stdout.write(`Built ${fileURLToPath(target)}\n`);
}
